const assert=require('node:assert/strict');
const {matches,summary,deadlines,csv}=require('../assets/js/account-insights');
const now=Date.parse('2026-10-25T00:00:00Z'),day=86400000;
const date=days=>new Date(now+days*day).toISOString();
const account={status:'active',features:{assessment:{enabled:true,canStart:true,expiresAt:date(3)},gaokao:{enabled:true,canQuery:true,expiresAt:date(30),queryCount:0}}};
assert(matches(account,'soon',now));assert(matches(account,'pending',now));assert(matches(account,'query-unused',now));
assert(!matches(account,'expired',now));
const done={...account,reportId:'report-test',features:{...account.features,assessment:{enabled:true,canStart:false,expiresAt:date(-20),viewUntil:date(8)}}};
assert(!matches(done,'expired',now));assert(!matches(done,'soon',now));
assert(!matches(done,'pending',now));
const expired={...done,features:{...done.features,assessment:{...done.features.assessment,viewUntil:date(0)}}};
assert(matches(expired,'expired',now));assert(!matches(expired,'soon',now));
const disabled={...account,status:'disabled'};
assert.deepEqual(deadlines(disabled,now),[]);
const boundary={status:'active',features:{gaokao:{enabled:true,canQuery:true,expiresAt:date(7),queryCount:1}}};
assert(matches(boundary,'soon',now));assert(!matches(boundary,'query-unused',now));
assert(!matches({features:{gaokao:{enabled:false,expiresAt:date(1)}}},'soon',now));
assert.deepEqual(summary([account,done,expired,boundary],now),{total:4,pending:1,completed:2,queryUnused:3,soon:2,expired:1});
const output=csv([['=1+1',' \t@SUM(1)','a"b','x,y','多行\n内容',0]]);
assert(output.startsWith('\uFEFF"\'=1+1"'));assert(output.includes('"\' \t@SUM(1)"'));assert(output.includes('"a""b"'));assert(output.endsWith(',"0"'));
